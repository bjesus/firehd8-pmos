import mmap, os, struct
f = os.open("/dev/mem", os.O_RDONLY | os.O_SYNC)
def rd(base, offs):
    m = mmap.mmap(f, 0x1000, mmap.MAP_SHARED, mmap.PROT_READ, offset=base)
    return " ".join("%03x=%08x"%(o, struct.unpack_from("<I", m, o)[0]) for o in offs)
